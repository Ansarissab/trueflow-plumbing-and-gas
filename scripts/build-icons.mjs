// Build src/components/icons.ts from lucide-static.
// Usage: node scripts/build-icons.mjs
import { readFile, writeFile } from "node:fs/promises";
import { mkdirSync } from "node:fs";
import { existsSync } from "node:fs";
import path from "node:path";

const ICON_DIR = path.resolve("node_modules/lucide-static/icons");
const OUT = path.resolve("src/components/icons.ts");

// logical name -> candidate lucide-static file names (first existing wins)
const WANTED = {
  droplet: ["droplet"],
  wrench: ["wrench"],
  flame: ["flame"],
  hot: ["thermometer-sun", "thermometer"],
  shower: ["shower-head", "showerhead"],
  phone: ["phone-call", "phone"],
  pin: ["map-pin"],
  clock: ["clock"],
  shield: ["shield-check"],
  check: ["check"],
  checkCircle: ["circle-check-big", "circle-check", "check-circle-2", "check-circle"],
  star: ["star"],
  alert: ["triangle-alert", "alert-triangle"],
  arrow: ["arrow-right"],
  chevron: ["chevron-down"],
  menu: ["menu"],
  x: ["x"],
  badge: ["badge-check"],
  wallet: ["wallet", "banknote", "badge-dollar-sign"],
  calendar: ["calendar-check"],
  message: ["message-square", "message-circle"],
  sparkles: ["sparkles"],
  building: ["building-2", "building", "briefcase"],
  quote: ["quote"],
};

if (!existsSync(ICON_DIR)) {
  console.error(`Error: ${ICON_DIR} not found. Run npm install first.`);
  process.exit(1);
}

const out = [];
const missing = [];
for (const [logical, candidates] of Object.entries(WANTED)) {
  const file = candidates.find((c) => existsSync(path.join(ICON_DIR, `${c}.svg`)));
  if (!file) { missing.push(logical); continue; }
  let svg = await readFile(path.join(ICON_DIR, `${file}.svg`), "utf8");
  const m = svg.match(/<svg[^>]*>\s*([\s\S]*?)\s*<\/svg>/);
  if (!m) { missing.push(logical); continue; }
  // normalise whitespace so the emitted file stays tidy
  const body = m[1].replace(/\s*\n\s*/g, " ").replace(/\s{2,}/g, " ").trim();
  out.push(`  ${logical}: ${JSON.stringify(body)},`);
}

if (!out.length) {
  console.error("Error: no icons could be extracted.");
  process.exit(1);
}

const names = out.map((line) => line.trimStart().split(":")[0]).join(" | ");
const banner = "// AUTO-GENERATED by scripts/build-icons.mjs from lucide-static, do not edit by hand.\n";
const union = `export type IconName =\n  | ${names}\n;\n\n`;

const ts = `${banner}${union}export const ICON_VIEWBOX = "0 0 24 24";\n\nexport const ICONS: Record<IconName, string> = {\n${out.join("\n")}\n};\n`;

mkdirSync(path.dirname(OUT), { recursive: true });
await writeFile(OUT, ts, "utf8");
console.log(`Wrote ${OUT} with ${out.length} icons.`);
if (missing.length) console.warn(`Missing (not emitted): ${missing.join(", ")}`);
